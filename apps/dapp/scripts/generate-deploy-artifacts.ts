// Writes lib/deployArtifacts.ts: the keccak-256 of the creation code of each contract the
// Deploy screen may create, from the Foundry build. The screen refuses a contract creation whose
// code (the first `creationSize` bytes, before the constructor arguments) does not hash to one
// of these.
//
// The zero-knowledge verifier (contracts/zk, `FOUNDRY_PROFILE=zk forge build`) is linked to two
// libraries, so its code depends on their addresses. ZK_DEPLOY_ARTIFACTS pins each library's
// creation code, and the verifier's creation code with the library addresses blanked, together
// with where they sit. The screen fills in nothing itself: it reads the addresses out of the
// transaction, requires them to be the CREATE2 addresses of the pinned libraries, blanks them
// and compares the hash.
//
//   node scripts/generate-deploy-artifacts.ts [--check]
//
// --check compares instead of writing, and fails if the committed file is out of date.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { keccak256, type Hex } from "viem";

const here = dirname(fileURLToPath(import.meta.url));
const contractsDir = join(here, "..", "..", "..", "contracts");
const outPath = join(here, "..", "lib", "deployArtifacts.ts");
const check = process.argv.includes("--check");

const NAMES = [
  "ARLVestingWallet",
  "ARLTimelock",
  "ARLToken",
  "ARLJobs",
  "ARLVerifiedEvaluator",
  "ComputePayment",
  "ARLStakingRewards",
  "ARLAnonymousSignal",
] as const;

const ZK_SOURCE = "ARLSemaphoreVerifier.sol";
const ZK_LIBRARIES = ["RelationsLib", "ZKTranscriptLib"] as const;

interface ForgeArtifact {
  bytecode: {
    object: Hex;
    linkReferences?: Record<string, Record<string, { start: number; length: number }[]>>;
  };
  abi: { type: string; inputs?: { type: string; components?: unknown[] }[] }[];
}

const entries = NAMES.map((name) => {
  const a = JSON.parse(
    readFileSync(join(contractsDir, "out", `${name}.sol`, `${name}.json`), "utf8"),
  ) as ForgeArtifact;
  const ctor = a.abi.find((x) => x.type === "constructor");
  return [
    name,
    {
      creationHash: keccak256(a.bytecode.object),
      creationSize: (a.bytecode.object.length - 2) / 2,
      constructorInputs: ctor?.inputs ?? [],
    },
  ];
});

const zkArtifact = (name: string) =>
  JSON.parse(
    readFileSync(join(contractsDir, "out", ZK_SOURCE, `${name}.json`), "utf8"),
  ) as ForgeArtifact;

const libraries = ZK_LIBRARIES.map((name) => {
  const code = zkArtifact(name).bytecode.object;
  return [name, { creationHash: keccak256(code), creationSize: (code.length - 2) / 2 }];
});

// Unlinked code holds a 20-byte placeholder (`__$…$__`) wherever a library address goes.
const verifier = zkArtifact("HonkVerifier").bytecode;
const links = Object.values(verifier.linkReferences ?? {})
  .flatMap((byName) =>
    Object.entries(byName).flatMap(([library, places]) =>
      places.map((p) => ({ library, start: p.start })),
    ),
  )
  .sort((a, b) => a.start - b.start);
if (
  links.length !== ZK_LIBRARIES.length ||
  ZK_LIBRARIES.some((l) => links.filter((x) => x.library === l).length !== 1)
) {
  throw new Error("HonkVerifier is expected to link RelationsLib and ZKTranscriptLib once each");
}
let blanked: string = verifier.object;
for (const { start } of links) {
  const at = 2 + start * 2;
  if (!blanked.slice(at, at + 40).startsWith("__$")) {
    throw new Error(`HonkVerifier has no library placeholder at byte ${String(start)}`);
  }
  blanked = blanked.slice(0, at) + "0".repeat(40) + blanked.slice(at + 40);
}
const zk = {
  libraries: Object.fromEntries(libraries),
  HonkVerifier: {
    blankedCreationHash: keccak256(blanked as Hex),
    creationSize: (blanked.length - 2) / 2,
    links,
  },
};

const source = `/**
 * Generated by scripts/generate-deploy-artifacts.ts from the Foundry build. Do not edit by hand.
 */
export const DEPLOY_ARTIFACTS = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;

/**
 * The zero-knowledge verifier and its two libraries (contracts/zk). \`blankedCreationHash\` is the
 * hash of the verifier's creation code with the 20 bytes at each link set to zero.
 */
export const ZK_DEPLOY_ARTIFACTS = ${JSON.stringify(zk, null, 2)} as const;
`;

const normalise = (t: string) =>
  t
    .replace(/\s+/g, "")
    .replace(/,([}\]])/g, "$1")
    .replace(/"(\w+)":/g, "$1:");

if (check) {
  if (normalise(readFileSync(outPath, "utf8")) !== normalise(source)) {
    console.error(`${outPath} is out of date: run node scripts/generate-deploy-artifacts.ts`);
    process.exit(1);
  }
  console.log("deployArtifacts.ts matches the Foundry build");
} else {
  writeFileSync(outPath, source);
  console.log(`wrote ${outPath} (format it with prettier)`);
}
